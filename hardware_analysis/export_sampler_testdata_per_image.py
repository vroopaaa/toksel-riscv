#!/usr/bin/env python3
"""
Per-image variant of export_sampler_testdata.py, for large image sets (e.g. the 300 COCO
val2017 images used by measure_quantization_agreement.py).

Same map (proxy MobileNetV3 L2 energy, or --checkpoint), same quantisation and same golden
greedy as export_sampler_testdata.py (its functions are reused), but:
  - writes one C header per image, <out>/<G>x<G>/img_<id>.h, instead of one header for all
    images (a 300-image 64x64 header would be ~6 MB, recompiled for every emulator run),
  - builds the proxy backbone once instead of once per image,
  - no .txt matrices and no preview.png.

Each header defines FX_GRID / FX_BITS / FX_LEVELS, img_<id>_F_q<B>[G*G] and
img_<id>_greedy_K<K>[n], the same names as the combined header, so the RISC-V greedy code
and run_cycles.py (--data-dir) use it unchanged.

Usage:
  python export_sampler_testdata_per_image.py coco_val2017_300/*.jpg --size 512  --bits 10 --K 128 256 --out sampler_testdata_10bit_coco300
  python export_sampler_testdata_per_image.py coco_val2017_300/*.jpg --size 1024 --bits 10 --K 128 256 --out sampler_testdata_10bit_coco300

Does NOT modify any original files.
"""

import os
import argparse

import numpy as np
import torch

import export_sampler_testdata as ex


def make_proxy():
    import timm
    bb = timm.create_model("mobilenetv3_small_050", pretrained=True, features_only=True, out_indices=(3,)).eval()
    mean = torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
    std = torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)

    @torch.no_grad()
    def proxy_map(x):
        feat = bb((x - mean) / std)[0]
        return feat.pow(2).sum(1).sqrt()[0].numpy()
    return proxy_map


def main():
    ap = argparse.ArgumentParser(description="Export per-image sampler test headers")
    ap.add_argument("images", nargs="+", help="image files")
    ap.add_argument("--out", required=True)
    ap.add_argument("--checkpoint", default=None, help="trained SparseViTDetector checkpoint (real S/O maps)")
    ap.add_argument("--K", type=int, nargs="+", default=[128, 256])
    ap.add_argument("--bits", type=int, default=10)
    ap.add_argument("--size", type=int, default=1024, help="input image size; grid = size / 16")
    ap.add_argument("--check-pytorch", action="store_true",
                    help="also check every golden list against the repo FixationSampler (slow)")
    args = ap.parse_args()

    ex.IMG, ex.G = args.size, args.size // 16   # export_sampler_testdata's functions read these
    G = ex.G
    L = 2 ** args.bits - 1
    tag, ctype = ("u8", "uint8_t") if args.bits == 8 else (f"q{args.bits}", "uint16_t")
    out_dir = os.path.join(args.out, f"{G}x{G}")
    os.makedirs(out_dir, exist_ok=True)
    source = f"trained model {os.path.basename(args.checkpoint)}" if args.checkpoint else \
        "proxy: L2 energy of ImageNet-pretrained MobileNetV3-Small-0.5 block-3 features"
    get_map = (lambda x: ex.model_map(x, args.checkpoint)) if args.checkpoint else make_proxy()

    mismatches = 0
    for path in sorted(args.images):
        name = "img_" + os.path.splitext(os.path.basename(path))[0]
        raw = get_map(ex.load_image(path))
        F = (raw - raw.min()) / (raw.max() - raw.min() + 1e-12)
        Fq = np.round(F * L).astype(np.uint8 if args.bits == 8 else np.uint16)
        lines = ["/* Generated by hardware_analysis/export_sampler_testdata_per_image.py */",
                 f"/* source image: {os.path.basename(path)} resized to {args.size}x{args.size}; map: {source} */",
                 "#include <stdint.h>", f"#define FX_GRID {G}", f"#define FX_BITS {args.bits}",
                 f"#define FX_LEVELS {L + 1}   /* number of score values = buckets */", "",
                 f"static const {ctype} {name}_F_{tag}[{G * G}] = {{"]
        lines += ["  " + ", ".join(str(v) for v in Fq[r]) + "," for r in range(G)]
        lines.append("};")
        for K in args.K:
            picks = ex.greedy(Fq, K)
            if args.check_pytorch and not ex.check_against_pytorch(Fq, K, picks):
                mismatches += 1
                print(f"{name} K={K}: golden does NOT match PyTorch FixationSampler")
            lines.append(f"static const uint16_t {name}_greedy_K{K}[{len(picks)}] = {{ " + ", ".join(map(str, picks)) + " };")
        with open(os.path.join(out_dir, f"{name}.h"), "w") as f:
            f.write("\n".join(lines) + "\n")
    print(f">> wrote {len(args.images)} headers to {out_dir}"
          + (f", {mismatches} PyTorch mismatches" if args.check_pytorch else ""))
    return 1 if mismatches else 0


if __name__ == "__main__":
    raise SystemExit(main())
