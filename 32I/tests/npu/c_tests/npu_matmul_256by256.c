#include <stdint.h>

// ---------------------------------------------------------------------
// Low-level MMIO helpers
// ---------------------------------------------------------------------

static inline void npu_write32(uint32_t addr, uint32_t val) {
    asm volatile (
        "sw %0, 0(%1)"
        :
        : "r"(val), "r"(addr)
        : "memory"
    );
}

// Loads/stores a 16x16 tile between memory (base address, rows
// row_stride_bytes apart -- the enclosing matrix's row width) and the
// NPU's Matrix A/B/result windows via the custom-0 (opcode 0x0B) strided
// tile-transfer instruction. Each call replaces what used to be a 256-word
// npu_write32/npu_move_word loop per tile.
static inline void npu_load_a(const int32_t* src, uint32_t row_stride_bytes) {
    asm volatile (".insn r 0x0B, 0, 0, zero, %0, %1" : : "r"(src), "r"(row_stride_bytes) : "memory");
}

static inline void npu_load_b(const int32_t* src, uint32_t row_stride_bytes) {
    asm volatile (".insn r 0x0B, 1, 0, zero, %0, %1" : : "r"(src), "r"(row_stride_bytes) : "memory");
}

static inline void npu_store_c(int32_t* dst, uint32_t row_stride_bytes) {
    asm volatile (".insn r 0x0B, 2, 0, zero, %0, %1" : : "r"(dst), "r"(row_stride_bytes) : "memory");
}

// Prints the n x n region of memory at src (e.g. the fully-assembled
// result matrix at RESULT_BASE_ADDR) -- a general memory print, not NPU
// internal state, so it shows the whole BIG_DIM x BIG_DIM result rather
// than just whichever 16x16 tile the NPU last touched.
static inline void npu_print(const int32_t* src, uint32_t n) {
    asm volatile (".insn r 0x0B, 3, 0, zero, %0, %1" : : "r"(src), "r"(n) : "memory");
}

